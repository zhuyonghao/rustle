    private static var calendar: Calendar {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "Asia/Shanghai") ?? .current
        return calendar
    }

    private static func relativeDate(daysAgo: Int, hour: Int) -> Date {
        let day = calendar.date(byAdding: .day, value: -daysAgo, to: Date()) ?? Date()
        return calendar.date(bySettingHour: hour, minute: 30, second: 0, of: day) ?? day
    }

    private static func dueDate(daysFromToday: Int) -> String {
        let date = calendar.date(byAdding: .day, value: daysFromToday, to: Date()) ?? Date()
        let formatter = DateFormatter()
        formatter.calendar = calendar
        formatter.locale = Locale(identifier: "zh_CN")
        formatter.timeZone = calendar.timeZone
        formatter.dateFormat = "M月d日"
        return formatter.string(from: date)
    }

    private static func segments(_ entries: [(TimeInterval, TimeInterval, String, String)]) -> [TranscriptSegment] {
        entries.map { TranscriptSegment(start: $0.0, duration: $0.1 - $0.0, text: $0.3, speaker: $0.2) }
    }
